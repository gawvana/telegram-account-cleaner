def transform_text(text: str, style: str) -> str:
    if style not in FONTS_MAP:
        return text

    pattern = re.compile(
        r'(https?://\S+)|'
        r'(@\w+)|'
        r'(/\w+)|'
        r'([^\x00-\x7F]+)'
    )

    parts = []
    last_idx = 0
    for match in pattern.finditer(text):
        if match.start() > last_idx:
            sub = text[last_idx:match.start()]
            parts.append((sub, False))
            
        parts.append((match.group(0), True))
        last_idx = match.end()

    if last_idx < len(text):
        parts.append((text[last_idx:], False))

    if style == "upside_down":
        reversed_parts = []
        for p, is_preserved in reversed(parts):
            if is_preserved:
                reversed_parts.append(p)
            else:
                reversed_parts.append(p[::-1].translate(FONTS_MAP[style]))
        return "".join(reversed_parts)
    else:
        result = []
        for p, is_preserved in parts:
            if is_preserved:
                result.append(p)
            else:
                result.append(p.translate(FONTS_MAP[style]))
        return "".join(result)
